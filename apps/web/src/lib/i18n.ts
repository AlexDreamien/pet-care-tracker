const DICTIONARIES: Record<Locale, Record<MessageKey, string>> = { ru, en };

export type Translate = (key: MessageKey) => string;

export function translator(locale: Locale): Translate {
  const dictionary = DICTIONARIES[locale];
  // A missing key shows itself rather than an empty space, so it gets noticed and fixed.
  return (key) => dictionary[key] ?? key;
}

/**
 * Russian needs three forms where English needs two: 1 год, 2 года, 5 лет. Picking the
 * wrong one is the clearest sign an interface was translated by a machine.
 */
export function plural(locale: Locale, count: number, forms: [string, string, string]): string {
  if (locale === 'en') return Math.abs(count) === 1 ? forms[0] : forms[2];

  const absolute = Math.abs(count) % 100;
  const tens = absolute % 10;
  if (absolute > 10 && absolute < 20) return forms[2];
  if (tens > 1 && tens < 5) return forms[1];
  if (tens === 1) return forms[0];
  return forms[2];
}
